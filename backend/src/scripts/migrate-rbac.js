async function hasConstraint(connection, name) {
  const [rows] = await connection.execute(
    `SELECT COUNT(*) AS count FROM information_schema.table_constraints
     WHERE table_schema = current_schema() AND table_name = 'users' AND constraint_name = ?`,
    [name]
  );
  return Number(rows[0].count) > 0;
}

const connection = await pool.getConnection();
try {
  await connection.beginTransaction();
  await connection.execute(`CREATE TABLE IF NOT EXISTS roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description TEXT NOT NULL
  )`);
  await connection.execute(`CREATE TABLE IF NOT EXISTS permissions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(80) NOT NULL UNIQUE,
    description TEXT NOT NULL
  )`);
  await connection.execute(`CREATE TABLE IF NOT EXISTS role_permissions (
    role_id INTEGER NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permission_id INTEGER NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
  )`);
  await connection.execute(`CREATE TABLE IF NOT EXISTS user_permissions (
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    permission_id INTEGER NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    effect VARCHAR(5) NOT NULL CHECK (effect IN ('allow','deny')),
    granted_by INTEGER NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, permission_id)
  )`);

  for (const [code, name, description] of roles) {
    await connection.execute(
      `INSERT INTO roles (code, name, description) VALUES (?, ?, ?)
       ON CONFLICT (code) DO UPDATE SET name = EXCLUDED.name, description = EXCLUDED.description`,
      [code, name, description]
    );
  }
  for (const code of permissions) {
    await connection.execute(
      `INSERT INTO permissions (code, description) VALUES (?, ?)
       ON CONFLICT (code) DO NOTHING`,
      [code, code.replaceAll('.', ' ').replaceAll('_', ' ')]
    );
  }

  await connection.execute('ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check');
  await connection.execute(
    `UPDATE users SET role = CASE role
      WHEN 'admin' THEN 'procurement_admin'
      WHEN 'procurement' THEN 'procurement_admin'
      WHEN 'finance' THEN 'procurement_admin'
      WHEN 'approver' THEN 'supervisor'
      WHEN 'committee' THEN 'procurement_committee'
      WHEN 'inventory_officer' THEN 'storekeeper'
      ELSE role
    END`
  );
  if (!(await hasConstraint(connection, 'fk_users_role'))) {
    await connection.execute(
      'ALTER TABLE users ADD CONSTRAINT fk_users_role FOREIGN KEY (role) REFERENCES roles(code)'
    );
  }

  for (const [role, codes] of Object.entries(rolePermissions)) {
    await connection.execute(
      `INSERT INTO role_permissions (role_id, permission_id)
       SELECT r.id, p.id FROM roles r CROSS JOIN permissions p
       WHERE r.code = ? AND p.code = ANY(?)
       ON CONFLICT DO NOTHING`,
      [role, codes]
    );
  }

  await connection.commit();
  console.log('Six roles and database-backed permissions are ready.');
} catch (error) {
  await connection.rollback();
  throw error;
} finally {
  connection.release();
  await pool.end();
}
